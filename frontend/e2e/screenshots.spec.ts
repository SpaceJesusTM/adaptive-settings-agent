import { test } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { askAssistant, openTab, setup } from "./helpers";

// Paper/README figures. Same game, same catalogue, same starting settings for the A/B pair.
// REAL_AI=1 uses the configured local model for the adaptive answer; otherwise the labelled offline fallback.
const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "..", "..", "docs", "screenshots");
const REAL = process.env.REAL_AI === "1";
const mode = REAL ? "local" : "fallback";
const shot = (name: string) => resolve(OUT, name);
const GOAL = "I'm getting frame drops in VALORANT and want smoother competitive play. What should I change?";

test.beforeAll(() => mkdirSync(OUT, { recursive: true }));

test("A/B comparison: VALORANT, same state", async ({ page }) => {
  await setup(page, { condition: "baseline", aiMode: mode });
  await openTab(page, "Video", "Graphics Quality");
  await page.waitForTimeout(400);
  await page.screenshot({ path: shot("valorant_A_baseline_graphics_quality.png") });

  await page.getByRole("button", { name: "B · Adaptive" }).click();
  await page.waitForSelector(".assistant");
  await openTab(page, "Video", "Graphics Quality");
  await askAssistant(page, GOAL);
  await page.waitForTimeout(600);
  await page.screenshot({ path: shot("valorant_B_adaptive_graphics_quality.png") });

  const card = page.locator(".msg-assistant").last().locator(".rec-card").first();
  await card.getByRole("button", { name: "What it does & trade-offs" }).click();
  await card.getByRole("button", { name: "Show in settings" }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: shot("valorant_B_highlight_canonical_row.png") });

  const stageAll = page.locator(".msg-assistant").last().getByRole("button", { name: /Stage all/ });
  if (await stageAll.count()) await stageAll.click();
  else await card.getByRole("button", { name: "Stage for review" }).click();
  await page.waitForSelector(".tray.is-open .tray-item");
  await page.waitForTimeout(400);
  await page.screenshot({ path: shot("valorant_B_review_tray.png") });

  await page.getByRole("button", { name: /^Apply selected changes/ }).click();
  await page.waitForTimeout(800);
  await page.getByRole("button", { name: "History" }).click();
  await page.waitForSelector(".drawer");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("valorant_history_drawer.png") });
  writeFileSync(resolve(OUT, "README.md"), [
    "# Screenshots",
    "",
    `Generated by \`npx playwright test e2e/screenshots.spec.ts\` on ${new Date().toISOString()} (viewport 1440x900).`,
    `Assistant source for the adaptive figures: **${REAL ? "real local model (OLLAMA_MODEL from .env)" : "offline fallback (rule-based, NOT AI)"}** — the UI labels this on every answer.`,
    "All scenes use synthetic demo data (scenario `default` or `valorant_history_new_cs2`). These are simulations, not the real games.",
    "",
  ].join("\n"));
});

test("VALORANT General tab (Map + sections created by Patch 12.07)", async ({ page }) => {
  await setup(page, { condition: "baseline", aiMode: mode });
  await openTab(page, "General");
  await page.locator('[data-setting-id="val.general.rotate"]').scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("valorant_A_general_map.png") });
});

test("CS2 baseline, crosshair, and cross-game adaptive view", async ({ page }) => {
  await setup(page, { condition: "baseline", game: "cs2", aiMode: mode });
  await openTab(page, "Video", "Advanced Video");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("cs2_A_baseline_advanced_video.png") });
  await openTab(page, "Crosshair / Scopes");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("cs2_A_crosshair_scopes.png") });

  await setup(page, { scenario: "valorant_history_new_cs2", condition: "adaptive", game: "cs2", aiMode: mode });
  await openTab(page, "Video", "Advanced Video");
  await page.waitForSelector(".rn .rec-card");
  await page.locator(".rn .rec-card").first().getByRole("button", { name: "Show in settings" }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: shot("cs2_B_cross_game_relevant_now.png") });
});
