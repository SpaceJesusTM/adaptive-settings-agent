import { test } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { askAssistant, openExperimenter, openTab, setup } from "./helpers";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "..", "..", "docs", "screenshots");
const REAL = process.env.REAL_AI === "1";
const mode = REAL ? "local" : "fallback";
const shot = (name: string) => resolve(OUT, name);

test.beforeAll(() => mkdirSync(OUT, { recursive: true }));

test("Participant mode, A/B comparison, Adaptive Workspace & standalone view", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await setup(page, { scenario: "fresh_install_comprehensive", condition: "baseline", aiMode: mode });
  await openTab(page, "Video", "Graphics Quality");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("01_valorant_baseline_1440.png") });

  await openExperimenter(page);
  await page.getByRole("button", { name: "B · Adaptive" }).click();
  await page.waitForSelector(".assistant");
  // Return to clean participant view before taking participant screenshot
  await page.getByRole("button", { name: /^Experimenter/ }).click();
  await openTab(page, "Video", "Graphics Quality");
  await askAssistant(page, "I just installed VALORANT; configure everything for competitive FPS and clarity.");
  await page.waitForTimeout(400);
  await page.screenshot({ path: shot("02_valorant_participant_chat_autostaged.png") });

  await page.locator(".msg-assistant").last().getByRole("button", { name: /^Review \d+ changes?$/ }).click();
  await page.waitForSelector(".aw-workspace.is-open .tray-item");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("03_adaptive_workspace_changes.png") });

  await page.getByRole("tab", { name: /^Discover/ }).click();
  await page.waitForTimeout(250);
  await page.screenshot({ path: shot("04_adaptive_workspace_discover.png") });

  // Laptop 1280x720 responsive viewport
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByRole("tab", { name: /^Changes/ }).click();
  await page.waitForTimeout(250);
  await page.screenshot({ path: shot("05_responsive_1280x720.png") });
});

test("VALORANT Crosshair & CS2 HUD Edge Positions & Detached Workspace", async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await setup(page, { condition: "baseline", game: "valorant", aiMode: mode });
  await openTab(page, "Crosshair", "Primary");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("06_valorant_crosshair_editor.png") });

  await setup(page, { condition: "adaptive", game: "cs2", aiMode: mode });
  await openTab(page, "Video", "HUD Edge Positions");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("07_cs2_hud_edge_positions.png") });

  await page.goto("/?view=workspace&game=cs2");
  await page.waitForSelector(".standalone-shell");
  await page.waitForTimeout(300);
  await page.screenshot({ path: shot("08_standalone_workspace.png") });

  writeFileSync(
    resolve(OUT, "README.md"),
    [
      "# Screenshots",
      "",
      `Generated by \`PW_CHANNEL=chrome npx playwright test e2e/screenshots.spec.ts\` on ${new Date().toISOString()}.`,
      `Assistant source for the adaptive captures: **${REAL ? "real local model (OLLAMA_MODEL from .env)" : "offline fallback (rule-based, NOT AI)"}**.`,
      "All scenes use synthetic demo data.",
      "",
    ].join("\n"),
  );
});
