"""Generate docs/CATALOG_REPORT.md: every catalogue setting with path, domain, default status and provenance.

  python scripts/catalog_report.py
"""
from __future__ import annotations

import sys
from collections import Counter

from _common import ROOT, bootstrap_backend_imports, utf8_stdout


def esc(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def domain(s) -> str:
    if s.controlType in ("dropdown", "segmented", "preset"):
        opts = " / ".join(o.label for o in (s.validOptions or []))
        return opts + (" _(simulated list)_" if s.optionsSimulated else "")
    if s.controlType == "slider":
        unit = " (shown as %)" if s.display == "percent" else (f" {s.unit}" if s.unit else "")
        flag = "" if s.rangeVerified else " **range not verified**"
        return f"{s.min:g}–{s.max:g}, step {s.step:g}{unit}{flag}"
    return "key binding"


def default(s) -> str:
    d = s.verifiedDefault
    if d.value is None:
        return d.status
    shown = s.option_label(d.value) or d.value
    return f"{d.status}: {shown}"


def main() -> int:
    utf8_stdout()
    bootstrap_backend_imports()
    from app.catalog.loader import load_registry
    from app.config import get_settings

    reg = load_registry(get_settings().catalog_dir)
    lines = ["# Catalogue report (generated)", "",
             "Generated by `python scripts/catalog_report.py` from `data/catalogs/*.json`. Do not edit by hand.",
             "See `GAME_SETTINGS_AUDIT.md` for methodology, sources and known gaps.", ""]
    for game in reg.games:
        cat = reg.catalog(game)
        ss = cat.settings
        ver = Counter(s.verificationStatus for s in ss)
        lines += [f"## {cat.displayName} — catalogue {cat.catalogVersion} ({len(ss)} settings)", "",
                  "Verification: " + ", ".join(f"{k} **{v}**" for k, v in sorted(ver.items())), "",
                  "| ID | Canonical path | Control | Values / range | Default | Verification | AI may propose | Primary source (date) |",
                  "|---|---|---|---|---|---|---|---|"]
        for s in ss:
            src = cat.sources[s.sourceRefs[0]]
            path = esc(s.canonicalPath) + (" _(section inferred)_" if s.pathVerification == "inferred" else "")
            lines.append(f"| `{s.id}` | {path} | {s.controlType} | {esc(domain(s))} | {esc(default(s))} | {s.verificationStatus} | "
                         f"{'yes' if s.aiProposable else 'no'} | [{esc(src.title)[:60]}]({src.url}) ({src.date}) |")
        lines.append("")
        lines += ["### Sources", ""]
        for key, src in cat.sources.items():
            lines.append(f"- `{key}` — {esc(src.title)}. {esc(src.publisher)}, {src.date}. <{src.url}>" + (f" Note: {esc(src.note)}" if src.note else ""))
        lines.append("")
    out = ROOT / "docs" / "CATALOG_REPORT.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({sum(len(reg.settings(g)) for g in reg.games)} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
